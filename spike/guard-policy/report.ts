/**
 * Writes the measurement reports from /tmp/guard-measure/results.json (measure.ts):
 * - /tmp/guard-measure/REPORT.md (private, 0600): aggregates plus redacted real commands, grouped;
 * - spike/guard-policy/REPORT.md (in the repo): aggregate counts only, no command text.
 * `node spike/guard-policy/report.ts`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { COMMANDS_FILE, type Extracted, OUT_DIR } from "./extract.ts";
import { redact } from "./redact.ts";

const here = dirname(fileURLToPath(import.meta.url));
const BRANCH = "feature/x";
const { commands: real, stats } = JSON.parse(readFileSync(COMMANDS_FILE, "utf8")) as {
	commands: Extracted[];
	stats: Record<string, number>;
};
const { summary, realResults, spike } = JSON.parse(readFileSync(join(OUT_DIR, "results.json"), "utf8"));

type R = (typeof realResults)[number];
const main = realResults.filter((r: R) => r.main);
const sum = (xs: R[]) => xs.reduce((a: number, r: R) => a + r.count, 0);
const show = (i: number, width = 200) => {
	const s = redact(real[i].command).replace(/\n/g, "⏎").replace(/\|/g, "\\|").replace(/`/g, "ˋ");
	return `\`${s.length > width ? `${s.slice(0, width)}…` : s}\``;
};
/** A finding's group: its rule with "(if an expansion holds -r)" folded in. */
const group = (r: R) =>
	[
		...new Set(
			r.neu[BRANCH].findings.map((f: { rule: string }) => f.rule.replace(/ \(if an expansion holds -r\)/, "")),
		),
	]
		.sort()
		.join(" + ");

function table(rows: [string, ...(string | number)[]][], head: string[]): string {
	return [
		`| ${head.join(" | ")} |`,
		`|${head.map(() => "---").join("|")}|`,
		...rows.map((r) => `| ${r.join(" | ")} |`),
	].join("\n");
}

const s = summary.real;
const realTable = (scope: string) => {
	const v = s[scope];
	return table(
		Object.entries(v.byBranch).map(([b, x]: [string, any]) => [
			`branch \`${b}\``,
			`${x.old_ask.unique} / ${x.old_ask.total}`,
			`${x.new_ask.unique} / ${x.new_ask.total}`,
			`${x.new_ask_if_dirty.unique} / ${x.new_ask_if_dirty.total}`,
			x.newOnly,
		]),
		[
			"judged on",
			"0.1.3 asks (unique / total)",
			"new `ask`",
			"new `ask-if-dirty`",
			"new prompts 0.1.3 allowed (unique)",
		],
	);
};

// Groups of what the new policy still asks, with counts (unique) on the feature branch.
const asks = main.filter((r: R) => r.neu[BRANCH].verdict !== "allow");
const byGroup = new Map<string, R[]>();
for (const r of asks) byGroup.set(group(r), [...(byGroup.get(group(r)) ?? []), r]);
const groups = [...byGroup].sort((a, b) => b[1].length - a[1].length);

// Dropped: 0.1.3 asked, new allows.
const dropped = main.filter((r: R) => r.old[BRANCH] !== null && r.neu[BRANCH].verdict === "allow");
const droppedBy = new Map<string, R[]>();
for (const r of dropped) droppedBy.set(r.old[BRANCH], [...(droppedBy.get(r.old[BRANCH]) ?? []), r]);
const droppedTable = table(
	[...droppedBy]
		.sort((a, b) => b[1].length - a[1].length)
		.map(([k, rs]) => [
			k,
			rs.length,
			sum(rs),
			rs.filter((r) => r.truth?.policy.verdict === "allow").length,
			rs.filter((r) => r.truth && r.truth.policy.verdict !== "allow").length,
		]),
	["0.1.3 reason", "unique", "total", "bash-truth: nothing dangerous", "bash-truth: dangerous"],
);

const sp = summary.spike;
const spikeTable = table(
	[
		["rows", sp.rows],
		["bash-truth dangerous under 0.1.3's rules", sp.oldTruthDangerous],
		[
			"… still asked by the new policy",
			`${sp.stillAsk} (ask ${sp.stillAskByLevel.ask ?? 0}, ask-if-dirty ${sp.stillAskByLevel["ask-if-dirty"] ?? 0})`,
		],
		["… intentionally dropped (reflog-recoverable)", sp.intentionallyDropped],
		["… no longer caught (command text)", sp.notCaught.filter((x: any) => !x.envRow).length],
		[
			"… no longer caught (A-env: TMPDIR model, unchanged from 0.1.3)",
			sp.notCaught.filter((x: any) => x.envRow).length,
		],
		[
			"rows the new policy's own truth needs and the parser misses",
			sp.newTruthDowngraded.filter((x: any) => !x.envRow).length,
		],
	],
	["spike corpus", "count"],
);
const spikeDropped = table(
	Object.entries(sp.intentionallyDroppedByCategory).map(([k, v]) => [k, v as number]),
	["dropped category", "rows"],
);

const extraction = `Sessions: ${stats.files} session files under \`~/.pi/agent/sessions/\` (${stats.workerFiles} worker or subagent transcripts), ${stats.calls} bash calls after ${stats.repeatedIds} calls recorded twice (subagent transcript + parent) were counted once; ${real.length} unique commands. Main session: ${s["main session"].unique} unique / ${s["main session"].total} total.`;

const aggregate = `# Guard "ask only when really dangerous", step 1: measurement (aggregate counts)

Generated by \`node spike/guard-policy/report.ts\`; no command text (real commands stay outside the repo, in
\`/tmp/guard-measure/\`). Code: \`policy.ts\` (the prototype, over \`../guard-parser/shell-ast.ts\`), \`resolve.ts\`,
\`extract.ts\`, \`measure.ts\`, \`cases.ts\` (${"96"} hand-judged cases).

${extraction}

The session's branch at the time isn't recorded, so each command is judged twice: as if on \`feature/x\` and on \`main\`.

## Real sessions: prompts

Main-session commands:

${realTable("main session")}

All commands, incl. workers (workers keep today's hard blocks; shown for scale only):

${realTable("all (incl. workers)")}

## What the new policy still asks (main session, \`${BRANCH}\`, unique commands)

${table(
	groups.map(([g, rs]) => [g, rs.length, sum(rs), rs[0].neu[BRANCH].verdict]),
	["rules", "unique", "total", "level"],
)}

## 0.1.3 prompts the new policy drops (main session, \`${BRANCH}\`)

${droppedTable}

Every dropped command was run in the sandboxed bash-truth harness (stubs only): ${summary.confirm.ran} commands (0.1.3 asks on either branch, new policy allows on both); ${summary.confirm.failures.length} where \`rm\`/\`git\` received something the new rules would ask on.

## Spike corpus (782 rows): safety regression

${spikeTable}

${spikeDropped}
`;
writeFileSync(join(here, "REPORT.md"), aggregate);

// Private report: the same, plus every remaining prompt (redacted) and examples per group.
const detail = [
	aggregate.replace("(aggregate counts)", "(full, private)"),
	"## Every command the new policy still asks about (redacted)",
	"",
	...groups.flatMap(([g, rs]) => [
		`### ${g}: ${rs.length}`,
		"",
		...rs.map((r) => {
			const why = r.neu[BRANCH].findings
				.map((f: { rule: string; detail: string }) => redact(f.detail).replace(/\|/g, "\\|"))
				.slice(0, 3)
				.join("; ");
			return `- #${r.i} [${r.neu[BRANCH].verdict}; 0.1.3: ${r.old[BRANCH] ?? "allow"}] ${show(r.i)} — ${why}`;
		}),
		"",
	]),
	"## Dropped 0.1.3 prompts, 3 redacted examples per category",
	"",
	...[...droppedBy].flatMap(([k, rs]) => [
		`### ${k}: ${rs.length}`,
		"",
		...rs.slice(0, 3).map((r) => `- #${r.i} ${show(r.i, 160)} — bash-truth: ${r.truth?.policy.verdict ?? "not run"}`),
		"",
	]),
	"## Spike rows not caught",
	"",
	...sp.notCaught.map(
		(x: any) =>
			`- #${x.id}${x.envRow ? " (A-env)" : ""} \`${spike[x.id].command}\` — ${x.want.findings.map((f: any) => f.detail).join("; ")}`,
	),
	"",
];
writeFileSync(join(OUT_DIR, "REPORT.md"), detail.join("\n"), { mode: 0o600 });
console.log("wrote", join(here, "REPORT.md"), "and", join(OUT_DIR, "REPORT.md"));
