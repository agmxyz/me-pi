/**
 * Step 1b reports from /tmp/guard-measure/results1b.json (measure1b.ts):
 * - spike/guard-policy/REPORT-1b.md (in the repo): aggregate counts only, no command text;
 * - /tmp/guard-measure/REPORT-1b.md (private, 0600): plus every remaining prompt and every fallback row, redacted.
 * `node spike/guard-policy/report1b.ts`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { COMMANDS_FILE, type Extracted, OUT_DIR } from "./extract.ts";
import { redact } from "./redact.ts";

const here = dirname(fileURLToPath(import.meta.url));
const B = "feature/x";
const { commands: real } = JSON.parse(readFileSync(COMMANDS_FILE, "utf8")) as { commands: Extracted[] };
const { summary, real1b, spike } = JSON.parse(readFileSync(join(OUT_DIR, "results1b.json"), "utf8"));
type R = (typeof real1b)[number];

const t = (head: string[], rows: (string | number)[][]) =>
	[`| ${head.join(" | ")} |`, `|${head.map(() => "---").join("|")}|`, ...rows.map((r) => `| ${r.join(" | ")} |`)].join(
		"\n",
	);
const show = (i: number, w = 180) => {
	const s = redact(real[i].command).replace(/\n/g, "⏎").replace(/\|/g, "\\|").replace(/`/g, "ˋ");
	return `\`${s.length > w ? `${s.slice(0, w)}…` : s}\``;
};
const group = (r: R) =>
	[...new Set(r.neu[B].findings.map((f: { rule: string }) => f.rule.replace(/ \(if an expansion holds -r\)/, "")))]
		.sort()
		.join(" + ");

const s = summary;
const prompts = t(
	[
		"judged on",
		"0.1.3 asks",
		"step 1: ask + ask-if-dirty",
		"step 1b: ask + ask-if-dirty",
		"1b prompts 0.1.3 didn't have",
	],
	Object.entries(s.real.byBranch).map(([b, x]: [string, any]) => [
		`\`${b}\``,
		x.old_ask.unique,
		`${x.step1_ask.unique} + ${x.step1_ask_if_dirty.unique} = ${x.step1_ask.unique + x.step1_ask_if_dirty.unique}`,
		`**${x.new_ask.unique} + ${x.new_ask_if_dirty.unique} = ${x.new_ask.unique + x.new_ask_if_dirty.unique}**`,
		x.newOnly,
	]),
);
const sens = s.real.movedRepoSensitivity;
const changed = t(
	["change from step 1 (`feature/x`, unique)", "commands"],
	Object.entries(s.real.changedFromStep1).map(([k, v]) => [k, v as number]),
);
const mainRs = real1b.filter((r: R) => r.main);
const asks = mainRs.filter((r: R) => r.neu[B].verdict !== "allow");
const byGroup = new Map<string, R[]>();
for (const r of asks) byGroup.set(group(r), [...(byGroup.get(group(r)) ?? []), r]);
const groups = [...byGroup].sort((a, b) => b[1].length - a[1].length);
const sp = s.spike;

const aggregate = `# Guard policy, step 1b: the user's five decisions, re-measured (aggregate counts)

Generated by \`node spike/guard-policy/report1b.ts\` from \`measure1b.ts\`; no command text. Code: \`policy.ts\` (decisions
behind \`PolicyEnv\`), \`disk.ts\` (read-only lookups for real sessions), \`cases1b.ts\` (hand-judged cases on a fake disk),
\`rebind-check.ts\` (decision 3 against guard's rebinding rows). Step 1: \`REPORT.md\`.

**Approximation.** Decisions 1, 4, and 5 read the disk *now* (\`git rev-parse\`, \`git config\`), from each command's
session cwd; the sessions ran weeks ago. Directories that no longer exist resolve to their nearest existing parent
(${s.real.disk.missingDirs} such directories for repo roots); a bare push from a directory that no longer exists asks
(${s.real.disk.branchMissing} directories, ${s.real.disk.branchAskedMissing} commands). Decision 1 resolved
${s.real.disk.branchRead} directories' branches from disk: every bare push after \`cd\` in these sessions went to a
directory that has since been moved or deleted.

## Real sessions (main session, ${s.real.unique} unique / ${s.real.total} total commands)

${prompts}

${changed}

Sensitivity (not the headline): reading the one moved repo at its new place gives \`feature/x\` ${sens["feature/x"].ask} ask +
${sens["feature/x"].askIfDirty} ask-if-dirty.

Decision 2 (parse failure → guard 0.1.3's verdict): ${s.real.byBranch[B].fallbacks} commands took the fallback;
0.1.3 asked on ${s.real.byBranch[B].fallbackAsk} of them, so ${s.real.byBranch[B].fallbacks - s.real.byBranch[B].fallbackAsk} became
\`allow\`.

## What 1b still asks (\`${B}\`, unique)

${t(
	["rules", "unique", "level"],
	groups.map(([g, rs]) => [g, rs.length, rs[0].neu[B].verdict]),
)}

## Bash-truth confirmation

${s.confirm.ran} commands run in the sandbox (stubs only): every 0.1.3 prompt 1b allows on both branches, plus every
command 1b allows through the decision-2 fallback (${s.confirm.fallbackAllowed}). Judged by the 1b rules over what
\`rm\`/\`git\` received: **${s.confirm.failures.length} failures**. Newly dropped 0.1.3 prompts (asked in step 1, allowed
in 1b): ${s.confirm.newlyDropped}, all confirmed.

## Spike corpus (782 rows; a fake disk: the session cwd is a repo with a network \`origin\`)

${t(
	["", "rows"],
	[
		["bash-truth dangerous (0.1.3 rules)", sp.oldTruthDangerous],
		["… still asked", sp.stillAsk],
		["… dropped on purpose (reflog-recoverable)", sp.intentionallyDropped],
		["… not caught, command text", sp.notCaught.filter((x: any) => !x.envRow).length],
		["… not caught, A-env: TMPDIR model (unchanged)", sp.notCaught.filter((x: any) => x.envRow).length],
		["verdicts changed from step 1 (any decision)", sp.changedFromStep1.length],
		["rows that fail to parse (decision 2 fallback)", sp.parseFailRows],
		["… where the fallback allows a bash-truth dangerous row (decision 2 risk)", sp.decision2Risk.length],
	],
)}
`;
writeFileSync(join(here, "REPORT-1b.md"), aggregate);

const fallbackRows = mainRs.filter((r: R) => r.neu[B].fallbacks.length > 0);
const detail = [
	aggregate.replace("(aggregate counts)", "(full, private)"),
	"## Every command 1b still asks about (`feature/x`, redacted)",
	"",
	...groups.flatMap(([g, rs]) => [
		`### ${g}: ${rs.length}`,
		"",
		...rs.map(
			(r) =>
				`- #${r.i} [${r.neu[B].verdict}; step 1 ${r.s1[B]}; 0.1.3 ${r.old[B] ?? "allow"}] ${show(r.i)} — ${r.neu[
					B
				].findings
					.map((f: { detail: string }) => redact(f.detail).replace(/\|/g, "\\|"))
					.slice(0, 2)
					.join("; ")}`,
		),
		"",
	]),
	"## Decision 2 fallback rows (main session)",
	"",
	...fallbackRows.map(
		(r: R) =>
			`- #${r.i} [1b ${r.neu[B].verdict}; 0.1.3 ${r.neu[B].fallbacks.map((f: { reason: string | null }) => f.reason ?? "allow").join(", ")}; bash-truth ${r.truth?.policy.verdict ?? "not run (asks)"}] ${show(r.i, 140)}`,
	),
	"",
	"## Spike parse-failure rows",
	"",
	...spike
		.filter((x: any) => x.parseFails)
		.map(
			(x: any) => `- #${x.id} \`${x.command.replace(/\n/g, "⏎")}\` — 1b ${x.got.verdict}, bash-truth ${x.oldTruth}`,
		),
	"",
];
writeFileSync(join(OUT_DIR, "REPORT-1b.md"), detail.join("\n"), { mode: 0o600 });
console.log("wrote", join(here, "REPORT-1b.md"), "and", join(OUT_DIR, "REPORT-1b.md"));
